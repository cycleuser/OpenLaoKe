"""Generate the tool and command reference from the code itself.

A hand-written tool table goes stale the day after it is written. This walks the
registry and the command list and writes `docs/tool-reference.md`, so the
reference is regenerated rather than edited:

    python scripts/dump_tool_reference.py
    python scripts/dump_tool_reference.py --check   # non-zero if the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "tool-reference.md"


def build() -> str:
    sys.path.insert(0, str(ROOT))

    from openlaoke.commands.registry import get_all_commands, register_all
    from openlaoke.core.tool import ToolRegistry
    from openlaoke.tools.register import register_all_tools

    registry = ToolRegistry()
    register_all_tools(registry)
    register_all()

    tools = sorted(registry.get_all(), key=lambda tool: tool.name)
    commands = sorted(get_all_commands(), key=lambda command: command.name)

    lines = [
        "# Tool and command reference",
        "",
        "Generated by `scripts/dump_tool_reference.py`; do not edit by hand.",
        "",
        f"{len(tools)} tools, {len(commands)} slash commands, as registered on this host.",
        "Optional tools (Batch, Browser) only appear when their config flag is on.",
        "",
        "## Tools",
        "",
        "| Tool | Flags | Description |",
        "| --- | --- | --- |",
    ]
    for tool in tools:
        description = " ".join(tool.get_description().split())
        if len(description) > 220:
            description = description[:217] + "..."
        flags = []
        if tool.is_read_only:
            flags.append("read-only")
        if tool.is_destructive:
            flags.append("destructive")
        if getattr(tool, "requires_approval", False):
            flags.append("needs approval")
        lines.append(
            f"| `{tool.name}` | {', '.join(flags) or 'no'} | {description.replace('|', '/')} |"
        )

    lines += [
        "",
        "## Slash commands",
        "",
        "| Command | Aliases | Description |",
        "| --- | --- | --- |",
    ]
    for command in commands:
        aliases = ", ".join(f"`/{alias}`" for alias in command.aliases) or "-"
        lines.append(f"| `/{command.name}` | {aliases} | {command.description} |")

    lines += [
        "",
        "## Unattended mode (`/insomnia`)",
        "",
        "Off by default. When on, the REPL drains a task queue one turn after another",
        "without waiting for input, retries a failed turn with exponential backoff, and",
        "keeps the session bounded while it runs.",
        "",
        "| Command | What it does |",
        "| --- | --- |",
        "| `/insomnia on` / `off` | Switch the mode; the queue is kept either way |",
        "| `/insomnia add <task>` | Queue a task (turns the mode on) |",
        "| `/insomnia list` | Show the queue, with attempt counts |",
        "| `/insomnia clear` | Empty the queue |",
        "| `/insomnia log [lines]` | Show the run log (`~/.openlaoke/insomnia/<session>.log`) |",
        "| `/insomnia cost [usd\\|off]` | Cost cap, checked after every iteration (default $10) |",
        "| `/insomnia hours [n\\|off]` | Prune this session's tool output older than n hours",
        "  and no longer named by the live history (default 3) |",
        "| `/insomnia accept [on\\|off]` | Whether the run approves tool calls that would",
        "  otherwise prompt (default on) |",
        "",
        "Two rules matter for a run that lasts all night. A task is only taken out of the",
        "queue once it has finished, so a crash, a reboot or a kill leaves the unfinished",
        "task in place for the next start. And a tool call that would ask the operator is",
        "never asked: with `accept` on the run approves it and says so once per tool, and",
        "with `accept` off it denies the call instead of blocking on a prompt nobody is",
        "there to answer.",
        "",
        "Ctrl+C during a run stops the run and returns the prompt; the current task stays",
        "queued.",
        "",
        "## Notes",
        "",
        "- Every tool carries two extra arguments injected by the harness: `intent` (why the",
        "  call is being made, shown at the end of the tool line) and `accept_large_output`",
        "  (request the full body of a result the ledger withheld).",
        "- `Batch` and `Browser` are opt-in: see `enable_batch` and `enable_browser`.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    parser.add_argument("--out", default="", help="write somewhere else")
    args = parser.parse_args(argv)

    text = build()
    target = Path(args.out) if args.out else TARGET
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"{target} is out of date; run scripts/dump_tool_reference.py")
            return 1
        print(f"{target} is up to date")
        return 0

    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({len(text)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
